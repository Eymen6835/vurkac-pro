async function main() {
  console.log("🌱 Starte Seeding der ImmoMetrica MVP-Datenbank mit 25 realistischen Inseraten...");

  await prisma.priceHistory.deleteMany();
  await prisma.propertySource.deleteMany();
  await prisma.property.deleteMany();

  for (const item of seedProperties) {
    await prisma.property.create({
      data: {
        id: item.id,
        title: item.title,
        description: item.description,
        propertyType: item.propertyType,
        address: item.address,
        zipCode: item.zipCode,
        city: item.city,
        district: item.district,
        federalState: item.federalState,
        latitude: item.latitude,
        longitude: item.longitude,
        livingAreaSqm: item.livingAreaSqm,
        rooms: item.rooms,
        yearBuilt: item.yearBuilt,
        floor: item.floor,
        energyClass: item.energyClass,
        condition: item.condition,
        isRented: item.isRented,
        purchasePrice: item.purchasePrice,
        initialPrice: item.initialPrice,
        estimatedRentCold: item.estimatedRentCold,
        currentRentCold: item.currentRentCold,
        estimatedMarketValue: item.estimatedMarketValue,
        hoaTotalMonthly: item.hoaTotalMonthly,
        nonAllocatableHoa: item.nonAllocatableHoa,
        maintenanceReserve: item.maintenanceReserve,
        brokerFeePercent: item.brokerFeePercent,
        firstListedAt: daysAgo(item.daysOnline),
        sources: {
          create: item.sources.map((s) => ({
            portalName: s.portalName,
            externalId: s.externalId,
            sourceUrl: s.sourceUrl,
            listedPrice: s.listedPrice,
            brokerFeePercent: s.brokerFeePercent,
            firstSeenAt: daysAgo(s.firstSeenDaysAgo),
            lastSeenAt: new Date(),
            isActive: true,
          })),
        },
        priceHistory: {
          create: item.priceDrops.map((p) => ({
            recordedAt: daysAgo(p.daysAgo),
            price: p.price,
            changePercent: p.changePercent,
            portalName: p.portalName,
            note: p.note,
          })),
        },
      },
    });
  }

  const count = await prisma.property.count();
  const sourceCount = await prisma.propertySource.count();
  const historyCount = await prisma.priceHistory.count();

  console.log(
    `✅ Seeding abgeschlossen: ${count} Master-Inserate, ${sourceCount} Portal-Quellen (inkl. Dubletten) und ${historyCount} Preishistorien-Einträge angelegt.`
  );
}

main()
  .catch((e) => {
    console.error("❌ Fehler beim Seeding:", e);
    process.exit(1);
  })
  .finally(async () => {
    await prisma.$disconnect();
  });
